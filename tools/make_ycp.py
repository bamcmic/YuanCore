#!/usr/bin/env python3
"""make_ycp.py - 打包 YuanCore YCP1 应用包(stored zip + ycmanifest.json)

用法:
  python3 tools/make_ycp.py --elf apps/hello64.app --name hello \
      --entry hello.app --out apps/demo.ycp [--blob mode/demo_ycp_blob.h]

YCP1 规格:
  <name>.ycp = zip(仅 stored)
    ycmanifest.json   必需字段 name/version/main_dir/entry/author/description
    <main_dir>/entry  ELF64 可执行
"""
import json
import zipfile
import argparse

p = argparse.ArgumentParser()
p.add_argument("--elf", required=True, help="入口 ELF 文件")
p.add_argument("--name", required=True, help="应用名(字母数字下划线)")
p.add_argument("--entry", required=True, help="入口可执行文件名")
p.add_argument("--version", default="1.0")
p.add_argument("--author", default="bamcmic")
p.add_argument("--desc", default="YuanCore package")
p.add_argument("--main-dir", default="main", dest="main_dir")
p.add_argument("--out", required=True, help="输出 .ycp 路径")
p.add_argument("--blob", help="同时生成 C 数组头文件(内核内置用)")
a = p.parse_args()

manifest = {
    "name": a.name,
    "version": a.version,
    "main_dir": a.main_dir,
    "entry": a.entry,
    "author": a.author,
    "description": a.desc,
}

z = zipfile.ZipFile(a.out, "w", zipfile.ZIP_STORED)
z.writestr("ycmanifest.json", json.dumps(manifest, indent=2))
z.write(a.elf, a.main_dir + "/" + a.entry)
z.close()

size = len(open(a.out, "rb").read())
print("wrote %s (%d B): %s v%s -> %s/%s" %
      (a.out, size, a.name, a.version, a.main_dir, a.entry))

if a.blob:
    data = open(a.out, "rb").read()
    guard = a.blob.replace(".", "_").replace("/", "_").upper()
    sym = a.blob[a.blob.rfind("/") + 1:][:-2]   # mode/demo_ycp_blob.h -> demo_ycp_blob
    base = sym[:-5] if sym.endswith("_blob") else sym
    macro = base.upper() + "_LEN"
    with open(a.blob, "w") as f:
        f.write("/* auto-generated by tools/make_ycp.py - do not edit */\n")
        f.write("#ifndef %s\n#define %s\n" % (guard, guard))
        f.write("#define %s %d\n" % (macro, len(data)))
        f.write("static const unsigned char %s[] = {" % sym)
        for i in range(0, len(data), 16):
            f.write("\n  " + ",".join("0x%02X" % b for b in data[i:i + 16]) + ",")
        f.write("\n};\n#endif\n")
    print("wrote %s (blob %d B)" % (a.blob, len(data)))
